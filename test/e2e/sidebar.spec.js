import { test, expect } from "@playwright/test";
test("wide workspace fills remaining width and rail toggle preserves draft", async ({ page }) => {
  await page.setViewportSize({ width: 1920, height: 1080 });
  await page.goto("/?demo=1");
  const sidebar = page.locator(".pc-navigation-bar");
  const main = page.locator(".pc-main");
  await expect(sidebar).toHaveAttribute("data-collapsed", "false");
  const before = await main.boundingBox();
  expect(before.x + before.width).toBe(1920);
  expect(before.width).toBeGreaterThan(1440);
  await page.getByLabel("บันทึกการพิจารณา").fill("ร่างระหว่างย่อเมนู");
  await page.getByRole("button", { name: "ย่อเมนูด้านข้าง", exact: true }).click();
  await expect(sidebar).toHaveAttribute("data-collapsed", "true");
  const after = await main.boundingBox();
  expect(after.width).toBeGreaterThan(before.width);
  await expect(page.getByLabel("บันทึกการพิจารณา")).toHaveValue("ร่างระหว่างย่อเมนู");
  await page.getByRole("button", { name: "ข้อพิพาท", exact: true }).hover();
  await expect(page.getByRole("tooltip", { name: "ข้อพิพาท", exact: true })).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
});
test("mobile drawer traps focus, closes with Escape, and navigates without leaving content inert", async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto("/?demo=1");
  const open = page.getByRole("button", { name: "เปิดเมนูผู้รับรอง", exact: true });
  await open.click();
  const drawer = page.getByRole("dialog", { name: "เมนูผู้รับรอง", exact: true });
  await expect(drawer).toBeVisible();
  expect(await page.locator(".pc-workspace-body").evaluate(el => el.inert)).toBe(true);
  await drawer.getByRole("button", { name: "เชื่อมต่ออีกครั้ง", exact: true }).focus();
  await page.keyboard.press("Tab");
  await expect(drawer.getByRole("link", { name: "PetChain", exact: true })).toBeFocused();
  await page.keyboard.press("Escape");
  await expect(drawer).toHaveCount(0);
  await expect(open).toBeFocused();
  await open.click();
  await page.getByRole("button", { name: "มติกรรมการ", exact: true }).click();
  await expect(page.getByRole("heading", { name: "มติกรรมการ", exact: true, level: 1 })).toBeVisible();
  expect(await page.locator(".pc-workspace-body").evaluate(el => el.inert)).toBe(false);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
});
